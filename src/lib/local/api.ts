"use client";

import { baseConfig, slugify, starterConfig } from "../defaults";
import { buildPreviewHtml, buildBundle, downloadZip } from "./publish";
import { commitFiles, defaultPagesUrl, loadGitHubConfig } from "./github";
import {
  idbAll,
  idbByIndex,
  idbDelete,
  idbGet,
  idbPut,
  type PublishRecord,
  type StoredApp,
  type StoredAsset,
  type StoredNotification,
} from "./idb";
import { mediaUrl, rememberAsset } from "./media";
import type { AppConfig } from "../types";

/**
 * The studio talks to `/api/...` exactly as it did when a server backed it.
 * This interceptor answers those calls from IndexedDB (and GitHub for
 * publishing), so the whole product runs as static files on GitHub Pages.
 */

class HttpError extends Error {
  status: number;
  constructor(message: string, status = 400) {
    super(message);
    this.status = status;
  }
}

const encoder = new TextEncoder();

function json(data: unknown, status = 200): Response {
  return new Response(JSON.stringify(data), {
    status,
    headers: { "content-type": "application/json", "cache-control": "no-store" },
  });
}

function parseConfig(app: StoredApp): AppConfig {
  const parsed = JSON.parse(app.config) as AppConfig;
  return parsed;
}

async function publicUrlFor(app: StoredApp): Promise<string> {
  const gh = await loadGitHubConfig();
  const base = gh?.pagesUrl?.trim() || (gh ? defaultPagesUrl(gh.owner, gh.repo) : "");
  if (!base) return app.publishedUrl ?? "";
  return `${base.replace(/\/+$/, "")}/apps/${app.slug}/`;
}

async function uniqueSlug(name: string, exceptId?: string): Promise<string> {
  const apps = await idbAll<StoredApp>("apps");
  const base = slugify(name) || "app";
  let candidate = base;
  let n = 2;
  while (apps.some((app) => app.slug === candidate && app.id !== exceptId)) {
    candidate = `${base}-${n++}`;
  }
  return candidate;
}

async function summarize(app: StoredApp) {
  const config = parseConfig(app);
  return {
    id: app.id,
    slug: app.slug,
    name: config.name,
    status: app.status,
    version: app.version,
    publishedAt: app.publishedAt,
    createdAt: app.createdAt,
    updatedAt: app.updatedAt,
    pages: config.pages.length,
    blocks: config.pages.reduce((total, page) => total + page.blocks.length, 0),
    icon: config.branding.icon ? mediaUrl(config.branding.icon.id) : null,
    primary: config.theme.primary,
    description: config.description,
    subscribers: 0,
    submissions: 0,
    scheduled: 0,
    publicUrl: await publicUrlFor(app),
  };
}

async function loadApp(id: string): Promise<StoredApp> {
  const app = await idbGet<StoredApp>("apps", id);
  if (!app) throw new HttpError("That app no longer exists", 404);
  return app;
}

async function requireGitHub() {
  const gh = await loadGitHubConfig();
  if (!gh?.token || !gh.owner || !gh.repo) {
    throw new HttpError("Connect your GitHub repository on the Publish tab first", 400);
  }
  return gh;
}

async function publishApp(id: string) {
  const app = await loadApp(id);
  const gh = await requireGitHub();
  const config = parseConfig(app);
  const base = (gh.pagesUrl?.trim() || defaultPagesUrl(gh.owner, gh.repo)).replace(/\/+$/, "");
  const publicUrl = `${base}/apps/${app.slug}/`;
  const bundle = await buildBundle(config, { appId: app.id, slug: app.slug, publicUrl });

  const prefix = `apps/${app.slug}/`;
  const files = bundle.files.map((file) => ({ path: `${prefix}${file.path}`, data: file.data }));
  const previous = (app.publishedFiles ?? []).filter((path) => !files.some((file) => file.path === path));
  const outcome = await commitFiles({
    config: gh,
    files,
    remove: previous,
    message: `Publish ${config.name}\n\nGenerated by App Maker.`,
  });

  const version = app.version + 1;
  const next: StoredApp = {
    ...app,
    status: "published",
    version,
    publishedAt: new Date().toISOString(),
    publishedFiles: files.map((file) => file.path),
    publishedUrl: publicUrl,
    config: app.config,
  };
  await idbPut("apps", next);
  const record: PublishRecord = {
    app_id: app.id,
    files: files.length,
    bytes: files.reduce((total, file) => total + file.data.length, 0),
    published_at: next.publishedAt!,
    url: publicUrl,
  };
  await idbPut("publishes", record);

  return {
    files: files.length,
    bytes: record.bytes,
    publicUrl,
    warnings: [...bundle.warnings, ...outcome.warnings],
    version,
    commit: outcome.commitUrl,
  };
}

async function unpublishApp(id: string) {
  const app = await loadApp(id);
  const gh = await requireGitHub();
  const files = app.publishedFiles ?? [];
  if (files.length) {
    await commitFiles({
      config: gh,
      files: [],
      remove: files,
      message: `Take ${app.name} offline\n\nGenerated by App Maker.`,
    });
  }
  await idbPut("apps", {
    ...app,
    status: "draft",
    publishedAt: null,
    publishedFiles: [],
    publishedUrl: "",
  } satisfies StoredApp);
}

async function exportZip(id: string): Promise<Response> {
  const app = await loadApp(id);
  const config = parseConfig(app);
  const gh = await loadGitHubConfig();
  const base = gh ? (gh.pagesUrl || defaultPagesUrl(gh.owner, gh.repo)).replace(/\/+$/, "") : "";
  const bundle = await buildBundle(config, {
    appId: app.id,
    slug: app.slug,
    publicUrl: base ? `${base}/apps/${app.slug}/` : "",
  });
  const { makeZip } = await import("../zip");
  const zip = makeZip(bundle.files.map((file) => ({ name: file.path, data: file.data })));
  const copy = new Uint8Array(zip.length);
  copy.set(zip);
  return new Response(copy, {
    headers: {
      "content-type": "application/zip",
      "content-disposition": `attachment; filename="${app.slug}.zip"`,
      "cache-control": "no-store",
    },
  });
}

async function handle(path: string, method: string, request: Request): Promise<Response> {
  // ---- apps -------------------------------------------------------------
  if (path === "/api/apps" && method === "GET") {
    const apps = await idbAll<StoredApp>("apps");
    const notifications = await idbAll<StoredNotification>("notifications");
    const summaries = await Promise.all(
      apps
        .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
        .map(async (app) => ({
          ...(await summarize(app)),
          scheduled: notifications.filter((n) => n.app_id === app.id && n.status === "scheduled").length,
        })),
    );
    return json({
      apps: summaries,
      totals: {
        apps: summaries.length,
        published: summaries.filter((app) => app.status === "published").length,
        subscribers: 0,
        submissions: 0,
        scheduled: notifications.filter((n) => n.status === "scheduled").length,
      },
    });
  }

  if (path === "/api/apps" && method === "POST") {
    const body = (await request.json()) as { name?: string; template?: string };
    const name = (body.name ?? "").trim().slice(0, 60) || "Untitled app";
    const config = body.template && body.template !== "blank" ? starterConfig(body.template, name) : baseConfig(name);
    const now = new Date().toISOString();
    const app: StoredApp = {
      id: crypto.randomUUID(),
      slug: await uniqueSlug(name),
      name: config.name,
      config: JSON.stringify(config),
      status: "draft",
      version: 0,
      publishedAt: null,
      createdAt: now,
      updatedAt: now,
      publishedFiles: [],
      publishedUrl: "",
    };
    await idbPut("apps", app);
    return json({ app: { ...app, config } }, 201);
  }

  const appMatch = path.match(/^\/api\/apps\/([^/]+)(?:\/(.+))?$/);
  if (appMatch) {
    const id = appMatch[1]!;
    const rest = appMatch[2] ?? "";

    if (!rest && method === "GET") {
      const app = await loadApp(id);
      return json({ app: { ...app, config: parseConfig(app) } });
    }

    if (!rest && method === "PATCH") {
      const app = await loadApp(id);
      const body = (await request.json()) as { name?: string; config?: AppConfig; slug?: string };
      let config = body.config ?? parseConfig(app);
      if (body.name) config = { ...config, name: String(body.name).slice(0, 60) };
      const slug = body.slug ? await uniqueSlug(body.slug, app.id) : app.slug;
      const next: StoredApp = {
        ...app,
        slug,
        name: config.name,
        config: JSON.stringify(config),
        updatedAt: new Date().toISOString(),
      };
      await idbPut("apps", next);
      return json({ app: { ...next, config } });
    }

    if (!rest && method === "DELETE") {
      await idbDelete("apps", id);
      const notifications = await idbByIndex<StoredNotification>("notifications", "app_id", id);
      await Promise.all(notifications.map((row) => idbDelete("notifications", row.id)));
      await idbDelete("publishes", id);
      return json({ ok: true });
    }

    if (rest === "duplicate" && method === "POST") {
      const app = await loadApp(id);
      const config = parseConfig(app);
      const name = `${config.name} copy`.slice(0, 60);
      const now = new Date().toISOString();
      const copy: StoredApp = {
        ...app,
        id: crypto.randomUUID(),
        slug: await uniqueSlug(name),
        name,
        config: JSON.stringify({ ...config, name }),
        status: "draft",
        version: 0,
        publishedAt: null,
        publishedFiles: [],
        publishedUrl: "",
        createdAt: now,
        updatedAt: now,
      };
      await idbPut("apps", copy);
      return json({ app: { ...copy, config } }, 201);
    }

    if (rest === "publish" && method === "POST") return json(await publishApp(id));
    if (rest === "publish" && method === "DELETE") {
      await unpublishApp(id);
      return json({ ok: true });
    }
    if (rest === "export" && method === "GET") return exportZip(id);

    if (rest === "files" && method === "GET") {
      const app = await loadApp(id);
      return json({
        files: (app.publishedFiles ?? []).map((file) => ({
          path: file.replace(`apps/${app.slug}/`, ""),
          size: 0,
          updatedAt: app.publishedAt,
        })),
        totalBytes: 0,
      });
    }

    if (rest === "preview" && method === "GET") {
      const app = await loadApp(id);
      const html = await buildPreviewHtml(parseConfig(app), { appId: app.id, slug: app.slug });
      return new Response(html, { headers: { "content-type": "text/html; charset=utf-8" } });
    }
  }

  // ---- uploads & media --------------------------------------------------
  if (path === "/api/upload" && method === "POST") {
    const form = await request.formData();
    const file = form.get("file");
    if (!(file instanceof Blob)) throw new HttpError("No file was uploaded");
    const name = typeof form.get("name") === "string" ? String(form.get("name")) : (file as File).name || "image";
    const asset: StoredAsset = {
      id: crypto.randomUUID(),
      name,
      type: file.type || "image/png",
      size: file.size,
      blob: file,
      createdAt: new Date().toISOString(),
    };
    await idbPut("assets", asset);
    rememberAsset(asset);
    return json({
      asset: {
        id: asset.id,
        name: asset.name,
        type: asset.type,
        width: Number(form.get("width")) || undefined,
        height: Number(form.get("height")) || undefined,
      },
    });
  }

  const mediaMatch = path.match(/^\/api\/media\/([^/]+)$/);
  if (mediaMatch && method === "GET") {
    const asset = await idbGet<StoredAsset>("assets", mediaMatch[1]!);
    if (!asset) return new Response("Not found", { status: 404 });
    return new Response(asset.blob, {
      headers: { "content-type": asset.type, "cache-control": "no-store" },
    });
  }

  // ---- notifications (local queue only) ---------------------------------
  if (path === "/api/notifications" && method === "GET") {
    const rows = await idbAll<StoredNotification>("notifications");
    return json({ notifications: rows.sort((a, b) => a.send_at.localeCompare(b.send_at)), subscribers: 0 });
  }
  if (path.startsWith("/api/submissions") && method === "GET") {
    return json({ submissions: [] });
  }
  if (path === "/api/auth/logout" && method === "POST") return json({ ok: true });
  if (path.startsWith("/api/auth/")) return json({ ok: true });

  throw new HttpError(`No local handler for ${method} ${path} (static studio)`, 404);
}

let installed = false;

export function installLocalApi(): void {
  if (installed || typeof window === "undefined") return;
  installed = true;

  const basePath = (process.env.NEXT_PUBLIC_BASE_PATH ?? "").replace(/\/+$/, "");
  const original = window.fetch.bind(window);

  window.fetch = async (input: RequestInfo | URL, init?: RequestInit): Promise<Response> => {
    let url: URL;
    try {
      url = new URL(typeof input === "string" ? input : input instanceof URL ? input.href : input.url, window.location.href);
    } catch {
      return original(input as RequestInfo, init);
    }

    const path = basePath && url.pathname.startsWith(basePath) ? url.pathname.slice(basePath.length) : url.pathname;
    if (url.origin !== window.location.origin || !path.startsWith("/api/")) {
      return original(input as RequestInfo, init);
    }

    const request = input instanceof Request ? input.clone() : new Request(url.toString(), init);
    const method = (init?.method ?? request.method ?? "GET").toUpperCase();

    try {
      return await handle(path, method, request);
    } catch (error) {
      if (error instanceof HttpError) return json({ error: error.message }, error.status);
      return json({ error: (error as Error).message || "Something went wrong" }, 500);
    }
  };
}

